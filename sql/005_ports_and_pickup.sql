-- Spread legacy bookings across the two mapped demonstration ports so the map
-- visibly represents the existing paid/active yachts at both locations.
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM app_migrations WHERE version='007_balance_demo_bookings') THEN
        WITH targets AS (
            SELECT reservation_id,
                   CASE WHEN seq % 2 = 1
                     THEN (SELECT port_id FROM ports WHERE name='Учебная марина Ялта')
                     ELSE (SELECT port_id FROM ports WHERE name='Учебная марина Феодосия')
                   END AS port_id
            FROM (
                SELECT r.reservation_id,
                       row_number() OVER (ORDER BY r.start_at,r.reservation_id) AS seq
                FROM reservations r
                JOIN ports p ON p.port_id=r.port_id
                WHERE p.name IN ('Учебная марина Ялта','Учебная марина Феодосия')
                  AND r.status_code IN ('paid','active')
            ) numbered
        ), moved AS (
            UPDATE reservations r SET port_id=t.port_id
            FROM targets t
            WHERE r.reservation_id=t.reservation_id AND r.port_id IS DISTINCT FROM t.port_id
            RETURNING r.reservation_id,r.client_id,r.port_id
        )
        INSERT INTO notifications(user_id,title,message,notification_type,related_entity,related_id)
        SELECT c.user_id,'Порт оплаченной заявки',
               'Для оплаченной или активной заявки №'||m.reservation_id||' указан демонстрационный порт «'||p.name||'». Фактический адрес выдачи уточните у администратора.',
               'reservation','reservation',m.reservation_id
        FROM moved m
        JOIN clients c ON c.client_id=m.client_id
        JOIN ports p ON p.port_id=m.port_id;
        INSERT INTO app_migrations(version) VALUES('007_balance_demo_bookings');
    END IF;
END $$;

