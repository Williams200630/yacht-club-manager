      AND (ba.end_at IS NULL OR ba.end_at>r.start_at)
);
-- If an older database has a current berth but no berth-assignment history, use
-- that real current relationship as a fallback; never invent a port location.
UPDATE reservations r SET port_id=pt.port_id
FROM boats boat JOIN berths br ON br.berth_id=boat.current_berth_id
JOIN piers pr USING(pier_id) JOIN ports pt USING(port_id)
WHERE r.boat_id=boat.boat_id AND r.port_id IS NULL AND pr.is_active AND pt.is_active;
-- For already-paid demo bookings with no placement history/current berth, assign
-- clearly named demo ports in turn. No berth number is fabricated.
WITH unlocated AS (
    SELECT r.reservation_id,row_number() OVER (ORDER BY r.start_at,r.reservation_id) seq
    FROM reservations r
    WHERE r.port_id IS NULL AND r.status_code IN ('paid','active')
), targets AS (
    SELECT reservation_id,CASE WHEN seq % 2=1
        THEN (SELECT port_id FROM ports WHERE name='Учебная марина Ялта')
        ELSE (SELECT port_id FROM ports WHERE name='Учебная марина Феодосия') END port_id
    FROM unlocated
), updated AS (
    UPDATE reservations r SET port_id=t.port_id FROM targets t
    WHERE r.reservation_id=t.reservation_id
    RETURNING r.reservation_id,r.port_id
)
