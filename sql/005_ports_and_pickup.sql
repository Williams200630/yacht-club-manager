UPDATE reservations r SET port_id=(
    SELECT pt.port_id FROM berth_assignments ba
    JOIN berths br USING(berth_id) JOIN piers pr USING(pier_id) JOIN ports pt USING(port_id)
    WHERE ba.boat_id=r.boat_id AND ba.start_at<=r.start_at
      AND (ba.end_at IS NULL OR ba.end_at>r.start_at)
    ORDER BY ba.start_at DESC LIMIT 1
) WHERE r.port_id IS NULL AND EXISTS (
    SELECT 1 FROM berth_assignments ba
