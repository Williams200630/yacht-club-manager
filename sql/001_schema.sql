 JOIN reservation_statuses rs ON rs.code=r.status_code LEFT JOIN employees e ON e.employee_id=r.manager_id;

CREATE OR REPLACE VIEW vw_payment_summary AS
 SELECT r.reservation_id,r.client_id,r.total_amount AS charged,
 COALESCE(SUM(CASE WHEN p.status IN('confirmed','partially_refunded') THEN p.amount ELSE 0 END),0)
 - COALESCE((SELECT SUM(rf.amount) FROM refunds rf JOIN payments px USING(payment_id) WHERE px.reservation_id=r.reservation_id AND rf.status='processed'),0) AS paid,
 r.total_amount-(COALESCE(SUM(CASE WHEN p.status IN('confirmed','partially_refunded') THEN p.amount ELSE 0 END),0)
 - COALESCE((SELECT SUM(rf.amount) FROM refunds rf JOIN payments px USING(payment_id) WHERE px.reservation_id=r.reservation_id AND rf.status='processed'),0)) AS balance
 FROM reservations r LEFT JOIN payments p USING(reservation_id) GROUP BY r.reservation_id;

CREATE OR REPLACE VIEW vw_monthly_analytics AS
 WITH monthly AS (
  SELECT date_trunc('month',p.confirmed_at)::date AS month,
   SUM(p.amount) FILTER(WHERE p.status IN('confirmed','partially_refunded')) AS revenue,
   COUNT(DISTINCT p.reservation_id) FILTER(WHERE p.status='confirmed') AS paid_bookings
  FROM payments p WHERE p.confirmed_at IS NOT NULL GROUP BY 1
 ) SELECT month,revenue,paid_bookings,LAG(revenue) OVER(ORDER BY month) AS previous_revenue,
 revenue-LAG(revenue) OVER(ORDER BY month) AS revenue_delta FROM monthly;
CREATE OR REPLACE VIEW vw_client_statistics AS
 WITH r AS (SELECT client_id,COUNT(*) AS reservation_count,SUM(total_amount) AS booked_total,COUNT(*) FILTER(WHERE status_code='completed') AS completed_count FROM reservations GROUP BY client_id)
 SELECT c.client_id,c.first_name,c.last_name,COALESCE(r.reservation_count,0) AS reservation_count,
 COALESCE(r.booked_total,0) AS booked_total,COALESCE(r.completed_count,0) AS completed_count
 FROM clients c LEFT JOIN r USING(client_id);
CREATE OR REPLACE VIEW vw_boat_statistics AS
 WITH r AS (SELECT boat_id,COUNT(*) AS booking_count,SUM(total_amount) FILTER(WHERE status_code NOT IN('rejected','cancelled')) AS revenue,
  AVG(EXTRACT(EPOCH FROM(end_at-start_at))/3600) AS avg_hours FROM reservations GROUP BY boat_id),
 m AS (SELECT boat_id,SUM(cost) AS maintenance_cost FROM maintenance GROUP BY boat_id)
 SELECT b.boat_id,b.name AS boat_name,bt.name AS boat_type,COALESCE(r.booking_count,0) AS booking_count,
 COALESCE(r.revenue,0) AS revenue,COALESCE(m.maintenance_cost,0) AS maintenance_cost,r.avg_hours
 FROM boats b JOIN boat_types bt USING(boat_type_id) LEFT JOIN r USING(boat_id) LEFT JOIN m USING(boat_id);

CREATE OR REPLACE FUNCTION fn_calculate_reservation_total(p_boat_id BIGINT,p_client_id BIGINT,p_start TIMESTAMPTZ,p_end TIMESTAMPTZ,p_passengers INTEGER)
RETURNS TABLE(base_amount NUMERIC,discount_percent NUMERIC,capacity_ok BOOLEAN) LANGUAGE sql STABLE AS $$
 SELECT ROUND((CASE WHEN EXTRACT(EPOCH FROM(p_end-p_start))/3600>=24
  THEN CEIL(EXTRACT(EPOCH FROM(p_end-p_start))/86400)*b.daily_rate
  ELSE EXTRACT(EPOCH FROM(p_end-p_start))/3600*b.hourly_rate END)::numeric,2),
 COALESCE((SELECT mt.discount_percent FROM memberships ms JOIN membership_types mt USING(membership_type_id)
  WHERE ms.client_id=p_client_id AND ms.status='active' AND p_start::date BETWEEN ms.start_date AND ms.end_date ORDER BY ms.end_date DESC LIMIT 1),0),
 b.capacity>=p_passengers
 FROM boats b WHERE b.boat_id=p_boat_id AND p_end>p_start;
$$;

CREATE OR REPLACE FUNCTION fn_get_available_boats(p_start TIMESTAMPTZ,p_end TIMESTAMPTZ,p_passengers INTEGER DEFAULT 1)
RETURNS TABLE(boat_id BIGINT,name TEXT,model TEXT,boat_type TEXT,capacity INTEGER,daily_rate NUMERIC,cover_image TEXT)
LANGUAGE sql STABLE AS $$
 SELECT b.boat_id,b.name,b.model,bt.name,b.capacity,b.daily_rate,COALESCE(i.image_path,'assets/boats/sailboat.svg')
 FROM boats b JOIN boat_types bt USING(boat_type_id)
 JOIN boat_statuses bs ON bs.boat_status_id=b.status_id
 LEFT JOIN LATERAL
  (SELECT image_path FROM boat_images WHERE boat_id=b.boat_id ORDER BY is_cover DESC,sort_order LIMIT 1) i ON TRUE
 WHERE NOT b.is_archived AND bs.code NOT IN('maintenance','unavailable') AND b.capacity>=p_passengers AND p_end>p_start
 AND NOT EXISTS(SELECT 1 FROM reservations r WHERE r.boat_id=b.boat_id AND r.status_code IN('pending','confirmed','awaiting_payment','paid','active') AND tstzrange(r.start_at,r.end_at,'[)') && tstzrange(p_start,p_end,'[)'))
 AND NOT EXISTS(SELECT 1 FROM maintenance m WHERE m.boat_id=b.boat_id AND m.status IN('planned','in_progress') AND daterange(m.start_at,COALESCE(m.end_at,DATE '9999-12-31'),'[]') && daterange(p_start::date,p_end::date,'[]'));
$$;
