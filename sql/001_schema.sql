CREATE OR REPLACE FUNCTION fn_get_monthly_revenue(p_from DATE,p_to DATE)
RETURNS TABLE(month DATE,revenue NUMERIC,bookings BIGINT,previous_revenue NUMERIC,change_percent NUMERIC)
LANGUAGE sql STABLE AS $$
  WITH m AS (SELECT date_trunc('month',p.confirmed_at)::date AS month_date,SUM(p.amount) AS revenue,COUNT(DISTINCT p.reservation_id) AS bookings
   FROM payments p WHERE p.status IN('confirmed','partially_refunded')
    AND p.confirmed_at::date BETWEEN (date_trunc('month',p_from)::date-interval '1 month')::date AND p_to GROUP BY 1),
  l AS (SELECT m.*,LAG(revenue) OVER(ORDER BY month_date) AS previous_revenue FROM m)
  SELECT month_date,revenue,bookings,previous_revenue,CASE WHEN previous_revenue=0 THEN NULL ELSE ROUND(100*(revenue-previous_revenue)/previous_revenue,2) END
   FROM l WHERE month_date>=date_trunc('month',p_from)::date ORDER BY month_date;
$$;
CREATE OR REPLACE FUNCTION fn_get_fleet_utilization(p_from DATE,p_to DATE)
RETURNS TABLE(boat_id BIGINT,boat_name TEXT,rental_hours NUMERIC,available_hours NUMERIC,utilization_percent NUMERIC)
LANGUAGE sql STABLE AS $$
 SELECT b.boat_id,b.name,COALESCE(SUM(EXTRACT(EPOCH FROM(LEAST(r.end_at,p_to::timestamp+interval '1 day')-GREATEST(r.start_at,p_from::timestamp)))/3600),0)::numeric,
 GREATEST(0,EXTRACT(EPOCH FROM((p_to+1-p_from)::integer*interval '1 day'))/3600)::numeric,
 CASE WHEN p_to<p_from THEN 0 ELSE ROUND(100*COALESCE(SUM(EXTRACT(EPOCH FROM(LEAST(r.end_at,p_to::timestamp+interval '1 day')-GREATEST(r.start_at,p_from::timestamp)))/3600),0)/GREATEST(1,(p_to-p_from+1)*24),2) END
 FROM boats b LEFT JOIN reservations r ON r.boat_id=b.boat_id AND r.status_code NOT IN('rejected','cancelled','expired') AND r.end_at>=p_from AND r.start_at<p_to::timestamp+interval '1 day'
 GROUP BY b.boat_id;
$$;
CREATE OR REPLACE FUNCTION fn_get_boat_popularity(p_from DATE,p_to DATE)
RETURNS TABLE(boat_id BIGINT,boat_name TEXT,bookings BIGINT,revenue NUMERIC,rank_no BIGINT)
LANGUAGE sql STABLE AS $$
 SELECT b.boat_id,b.name,COUNT(r.reservation_id),COALESCE(SUM(r.total_amount),0),RANK() OVER(ORDER BY COUNT(r.reservation_id) DESC)
 FROM boats b LEFT JOIN reservations r ON r.boat_id=b.boat_id AND r.created_at::date BETWEEN p_from AND p_to AND r.status_code NOT IN('rejected','cancelled')
 GROUP BY b.boat_id ORDER BY 5;
$$;

CREATE OR REPLACE FUNCTION trg_reservation_history() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor BIGINT; BEGIN
 actor:=NULLIF(current_setting('app.user_id',true),'')::bigint;
 IF TG_OP='INSERT' THEN INSERT INTO reservation_status_history(reservation_id,new_status_code,changed_by,note) VALUES(NEW.reservation_id,NEW.status_code,actor,'Заявка создана');
  RETURN NEW;
 ELSIF NEW.status_code IS DISTINCT FROM OLD.status_code THEN
  INSERT INTO reservation_status_history(reservation_id,old_status_code,new_status_code,changed_by,note) VALUES(NEW.reservation_id,OLD.status_code,NEW.status_code,actor,COALESCE(NEW.cancellation_note,''));
 END IF; RETURN NEW; END $$;
DROP TRIGGER IF EXISTS reservations_status_history ON reservations;
CREATE TRIGGER reservations_status_history AFTER INSERT OR UPDATE OF status_code ON reservations FOR EACH ROW EXECUTE FUNCTION trg_reservation_history();

CREATE OR REPLACE FUNCTION trg_receipt_on_confirmed_payment() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status='confirmed' AND (TG_OP='INSERT' OR OLD.status IS DISTINCT FROM NEW.status) THEN
  INSERT INTO receipts(payment_id,receipt_number,total_amount)
  VALUES(NEW.payment_id,'YC-'||to_char(now(),'YYYYMMDD')||'-'||lpad(NEW.payment_id::text,7,'0'),NEW.amount)
  ON CONFLICT(payment_id) DO NOTHING;
 END IF; RETURN NEW; END $$;
DROP TRIGGER IF EXISTS payment_receipt ON payments;
CREATE TRIGGER payment_receipt AFTER INSERT OR UPDATE OF status ON payments FOR EACH ROW EXECUTE FUNCTION trg_receipt_on_confirmed_payment();

CREATE OR REPLACE FUNCTION trg_audit_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor BIGINT; entity BIGINT; payload JSONB; BEGIN
 actor:=NULLIF(current_setting('app.user_id',true),'')::bigint;
 payload:=CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 entity:=COALESCE((payload->>TG_ARGV[0])::bigint,0);
 INSERT INTO audit_log(user_id,action,entity_type,entity_id,details)
 VALUES(actor,lower(TG_OP),TG_TABLE_NAME,entity,payload-'password_hash');
 IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $$;
DO $$ DECLARE t TEXT; BEGIN FOREACH t IN ARRAY ARRAY['boats','reservations','payments','refunds','maintenance','services','berths','clients','employees','piers','memberships'] LOOP
 EXECUTE format('DROP TRIGGER IF EXISTS audit_%I ON %I',t,t);
 EXECUTE format('CREATE TRIGGER audit_%I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION trg_audit_change(%L)',t,t,
  CASE t WHEN 'boats' THEN 'boat_id' WHEN 'reservations' THEN 'reservation_id' WHEN 'payments' THEN 'payment_id' WHEN 'refunds' THEN 'refund_id'
   WHEN 'maintenance' THEN 'maintenance_id' WHEN 'services' THEN 'service_id' WHEN 'clients' THEN 'client_id' WHEN 'employees' THEN 'employee_id'
   WHEN 'piers' THEN 'pier_id' WHEN 'memberships' THEN 'membership_id' ELSE 'berth_id' END);
END LOOP; END $$;
