CREATE OR REPLACE VIEW vw_boat_catalog AS
 SELECT b.boat_id,b.name,b.model,bt.name AS boat_type,m.name AS manufacturer,s.name AS status_name,
 b.production_year,b.length,b.width,b.draft,b.capacity,b.cabin_count,b.bathroom_count,b.engine_power,
 b.hourly_rate,b.daily_rate,b.min_hours,b.deposit_amount,b.description,b.equipment,b.current_berth_id,
 COALESCE(img.image_path,'assets/boats/sailboat.svg') AS cover_image,
 COALESCE((SELECT array_agg(a.name ORDER BY a.name) FROM boat_amenities ba JOIN amenities a USING(amenity_id) WHERE ba.boat_id=b.boat_id),ARRAY[]::text[]) AS amenities,
 (SELECT COUNT(*) FROM reservations r WHERE r.boat_id=b.boat_id AND r.status_code IN('confirmed','awaiting_payment','paid','active','completed')) AS booking_count
 FROM boats b JOIN boat_types bt USING(boat_type_id) JOIN manufacturers m USING(manufacturer_id)
 JOIN boat_statuses s ON s.boat_status_id=b.status_id
 LEFT JOIN LATERAL(SELECT image_path FROM boat_images WHERE boat_id=b.boat_id ORDER BY is_cover DESC,sort_order,image_id LIMIT 1) img ON TRUE
 WHERE NOT b.is_archived;

CREATE OR REPLACE VIEW vw_active_reservations AS
 SELECT r.reservation_id,r.client_id,c.first_name||' '||c.last_name AS client_name,c.phone,u.email,
 r.boat_id,b.name AS boat_name,r.start_at,r.end_at,r.passenger_count,r.total_amount,r.status_code,rs.title AS status_title,
